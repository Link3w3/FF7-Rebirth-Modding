"""The checker's table of the 104 game shaders (gen/G_*.cpp): name, entry points, the Material uniform buffer's binding,
switches, and how its uniform expressions come from the vector parameters (uniform_expressions.json).
    mk_registry.py  ->  gen/registry.cpp, rb/rms_params.inc"""
import json, re, os

H = os.path.dirname(os.path.abspath(__file__))
R = os.path.dirname(H)
index = json.load(open(os.path.join(H, 'gen/index.json')))
sw = json.load(open(os.path.join(H, 'switches.json')))
ue = json.load(open(os.path.join(R, 'uniform_expressions.json')))
params = json.load(open('/work/remake_mat/rm/RM_Surface_params.json'))
VECS = [v[0] for v in params['vectors']]
TEXS = [t[0] for t in params['textures']]
SWS = sw['names']
SCALARS = ['RefractionDepthBias', '__SubsurfaceProfile']
# the instances' blend modes: the engine applies the opacity mask (discards) for masked and translucent ones
RMI = {e['name']: e for e in json.load(open(os.path.join(R, 'rmi_surface.json')))}
CLIP_MODES = ('BLEND_Masked', 'BLEND_Translucent', 'BLEND_Additive', 'BLEND_Modulate', 'BLEND_AlphaComposite',
              'BLEND_AlphaCompositeColored', 'BLEND_AlphaHoldout')


def comp_expr(e):
    """'P.x' / 'P' / 'append(...)' -> list of C++ component expressions."""
    e = e.strip()
    m = re.fullmatch(r'append\((.*)\)', e)
    if m:
        # split at the top-level comma
        s, depth = m.group(1), 0
        for i, ch in enumerate(s):
            if ch == '(':
                depth += 1
            elif ch == ')':
                depth -= 1
            elif ch == ',' and depth == 0:
                return comp_expr(s[:i]) + comp_expr(s[i + 1:])
        raise ValueError(e)
    m = re.fullmatch(r'(\w+)\.([xyzw]+)', e)
    if m:
        return ['P[%d].%s' % (VECS.index(m.group(1)), c) for c in m.group(2)]
    if e in VECS:
        return ['P[%d].%s' % (VECS.index(e), c) for c in 'xyzw']
    if e in SCALARS:
        return ['S[%d]' % SCALARS.index(e)]
    raise ValueError(e)


# the spliced copies of the lit translucent shaders (splice.py): the game's lighting on the rebuild's material values
SPL = {}
if os.path.exists(os.path.join(H, 'gen_s/index.json')):
    SPL = {e['name']: e['ns'] for e in json.load(open(os.path.join(H, 'gen_s/index.json')))}
out = ['// generated by mk_registry.py', '#include "../harness.hpp"', '#include <vector>', '#include <string>', 'using namespace cpuglsl;']
entries = []
for rec in index:
    ns, name = rec['ns'], rec['name']
    src = open(os.path.join(H, 'gen', ns + '.cpp')).read()
    m = re.search(r'static UBO& Material = ubo\("(\w+)"\);', src)
    mkey = m.group(1) if m else ''
    m = re.search(r'static UBO\w*& TranslucentBasePass\w* = ubo\w*\("(\w+)"\);', src)
    tkey = m.group(1) if m else ''
    out.append('namespace %s { void run(); void set_inputs(Inputs&); void get_outputs(Outputs&); }' % ns)
    sns = SPL.get(name)
    if sns:
        out.append('namespace %s { void run(); void set_inputs(Inputs&); void get_outputs(Outputs&); }' % sns)
    u = ue.get(name, {})
    lines = []
    for i, e in enumerate(u.get('vector', [])):
        c = comp_expr(e) + ['D(0.0)'] * 4
        lines.append('    M._m0[%d] = vec4(%s);' % (i, ', '.join(c[:4])))
    sc = u.get('scalar', [])
    for i, e in enumerate(sc):
        lines.append('    M._m0[%d].%s = %s;' % (len(u.get('vector', [])) + i // 4, 'xyzw'[i % 4], comp_expr(e)[0]))
    out.append('static void fill_%s(UBO& M, const vec4* P, const D* S) {\n%s\n}' % (ns, '\n'.join(lines)))
    on = sw['rmis'].get(name, [])
    clip = RMI[name]['overrides'].get('BlendMode') in CLIP_MODES
    spl = ('&%s::run, &%s::set_inputs, &%s::get_outputs' % (sns, sns, sns)) if sns else 'nullptr, nullptr, nullptr'
    entries.append('    {"%s", "%s", &%s::run, &%s::set_inputs, &%s::get_outputs, "%s", {%s}, &fill_%s, "%s", "%s", %s, %s},' % (
        name, ns, ns, ns, ns, mkey, ', '.join('"%s"' % s for s in on), ns, rec['vf'], tkey, 'true' if clip else 'false', spl))
out.append('''struct GameShader
{
    const char* name;
    const char* ns;
    void (*run)();
    void (*set_inputs)(Inputs&);
    void (*get_outputs)(Outputs&);
    const char* material_ubo;
    std::vector<std::string> switches;
    void (*fill_material)(UBO&, const vec4*, const D*);
    const char* vf;
    const char* translucent_ubo;
    bool clip;
    void (*srun)();
    void (*sset_inputs)(Inputs&);
    void (*sget_outputs)(Outputs&);
};
std::vector<GameShader> g_shaders = {''')
out.extend(entries)
out.append('};')
open(os.path.join(H, 'gen/registry.cpp'), 'w').write('\n'.join(out) + '\n')

# the rebuild's inputs, named as the Custom node's pins
os.makedirs(os.path.join(H, 'rb'), exist_ok=True)
inc = ['// generated by mk_registry.py: the Custom node inputs (textures T_*, vectors V_*, switches S_*)']
inc.append('#define RMS_TEXTURES(X) ' + ' '.join('X(%s)' % t for t in TEXS))
inc.append('#define RMS_VECTORS(X) ' + ' '.join('X(%s, %d)' % (v, i) for i, v in enumerate(VECS)))
inc.append('#define RMS_SWITCHES(X) ' + ' '.join('X(%s)' % s for s in SWS))
inc.append('static const char* RMS_VECTOR_NAMES[] = {%s};' % ', '.join('"%s"' % v for v in VECS))
inc.append('static const char* RMS_SWITCH_NAMES[] = {%s};' % ', '.join('"%s"' % s for s in SWS))
inc.append('static const int RMS_NUM_VECTORS = %d, RMS_NUM_SWITCHES = %d;' % (len(VECS), len(SWS)))
inc.append('static const char* RMS_SCALAR_NAMES[] = {%s};' % ', '.join('"%s"' % v for v in SCALARS))
open(os.path.join(H, 'rb/rms_params.inc'), 'w').write('\n'.join(inc) + '\n')
print(len(entries), 'shaders;', len(TEXS), 'textures', len(VECS), 'vectors', len(SWS), 'switches')
